export function softwareKnowledge(question: string, context: string): string {
  const query = `${question} ${context}`.toLowerCase()
  const hits = entries.filter((entry) => entry.tags.some((tag) => query.includes(tag)))
  return (
    `栖间知识版本${KNOWLEDGE_VERSION}。栖间是本地书桌陪伴软件，白纸=便签，笔筒=画板，单词卡=背词，台历=日历，手柄=游戏，平板=视频仓库。\n` +
    (hits.length ? hits : entries)
      .slice(0, 8)
      .map((entry) => entry.text)
      .join('\n')
  )
}

